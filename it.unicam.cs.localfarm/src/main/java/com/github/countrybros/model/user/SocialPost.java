package com.github.countrybros.model.user;

/**
 * Represents a generic social post.
 */
public class SocialPost {

    String title;
    String description;
    String link;

    public String getTitle() {
        return title;
    }

    public String getDescription() {
        return description;
    }

    public String getLink() {
        return link;
    }
}
